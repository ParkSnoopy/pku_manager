enum AppLanguage {
  ko('ko'),
  en('en'),
  zhHans('zh');

  const AppLanguage(this.code);
  final String code;
  Locale get locale => Locale(code);
  static const defaultLanguage = ko;
  static AppLanguage parse(String value) => values.firstWhere(
    (language) => language.code == value,
    orElse: () => defaultLanguage,
  );
}

